def _load_json(path: Path) -> dict[str, Any]:
    return json.loads(path.read_text(encoding="utf-8"))


def _parse_hex_int(value: Any) -> int:
    if isinstance(value, int):
        return value
    text = str(value).strip()
    if text.lower().startswith("0x"):
        return int(text, 16)
    return int(text, 10)


def _parse_hex_bytes(text: str) -> bytes:
    normalized = text.replace(" ", "").replace("\n", "").replace("\t", "")
    return bytes.fromhex(normalized)


def _upper_snake(text: str) -> str:
    cleaned = re.sub(r"[^0-9A-Za-z]+", "_", text)
    cleaned = re.sub(r"_+", "_", cleaned).strip("_")
    if not cleaned:
        return "UNNAMED"
    if cleaned[0].isdigit():
        cleaned = f"N_{cleaned}"
    return cleaned.upper()


def _swift_string(text: str) -> str:
    return text.replace("\\", "\\\\").replace("\"", "\\\"")


def _header_lines() -> list[str]:
    return [
        "// Auto-generated by script/bms_client_asset_tool.py",
        "// Source: docs/register_catalog.json",
        "// Do not edit manually.",
        "",
    ]


def _collect_register_constants(catalog: dict[str, Any]) -> list[tuple[str, str, int]]:
    constants: list[tuple[str, str, int]] = []
    for block in catalog["register_blocks"]:
        block_prefix = _upper_snake(block["id"])
        if "start_address" in block:
            constants.append((f"{block_prefix}_START", "uint16", _parse_hex_int(block["start_address"])))
        if "word_count" in block:
            constants.append((f"{block_prefix}_WORD_COUNT", "uint16", int(block["word_count"])))
        if "word_count_read" in block:
            constants.append((f"{block_prefix}_READ_WORD_COUNT", "uint16", int(block["word_count_read"])))
        if "magic_word" in block:
            constants.append((f"{block_prefix}_MAGIC", "uint16", _parse_hex_int(block["magic_word"])))

        for field in block.get("fields", []):
            field_prefix = f"{block_prefix}_{_upper_snake(field['id'])}"
            if "index" in field:
                constants.append((f"{field_prefix}_INDEX", "int", int(field["index"])))
            if "start_index" in field:
                constants.append((f"{field_prefix}_START_INDEX", "int", int(field["start_index"])))
            if "word_count" in field:
                constants.append((f"{field_prefix}_WORD_COUNT", "int", int(field["word_count"])))
            if "address" in field:
                constants.append((f"{field_prefix}_ADDRESS", "uint16", _parse_hex_int(field["address"])))
            if "start_address" in field:
                constants.append((f"{field_prefix}_START_ADDRESS", "uint16", _parse_hex_int(field["start_address"])))
            if "end_address" in field:
                constants.append((f"{field_prefix}_END_ADDRESS", "uint16", _parse_hex_int(field["end_address"])))

        for bit in block.get("bit_flags", []):
            constants.append((f"{block_prefix}_BIT_{_upper_snake(bit['key'])}", "int", int(bit["bit"])))

    return constants


def _render_swift(catalog: dict[str, Any]) -> str:
    lines = _header_lines()
    lines.append("import Foundation")
    lines.append("")
    lines.append("enum BMSGeneratedUUIDs {")
    lines.append(f"    static let SERVICE_UUID = \"{_swift_string(catalog['ble_transport']['gatt']['service_uuid'])}\"")
    lines.append(
        f"    static let REQUEST_CHARACTERISTIC_UUID = \"{_swift_string(catalog['ble_transport']['gatt']['request_characteristic_uuid'])}\""
    )
    lines.append(
        f"    static let RESPONSE_CHARACTERISTIC_UUID = \"{_swift_string(catalog['ble_transport']['gatt']['response_characteristic_uuid'])}\""
    )
    lines.append("}")
    lines.append("")
    lines.append("enum BMSGeneratedBLEConstraints {")
    lines.append(
        f"    static let DEFAULT_ATT_MTU: UInt16 = 0x{catalog['ble_transport']['link_constraints']['default_att_mtu']:04X}"
    )
    lines.append(
        "    static let SAFE_SINGLE_REQUEST_PAYLOAD_BYTES: Int = "
        f"{int(catalog['ble_transport']['link_constraints']['safe_single_request_payload_bytes'])}"
    )
    lines.append(
        "    static let RESPONSE_NOTIFY_FRAGMENT_BYTES: Int = "
        f"{int(catalog['ble_transport']['link_constraints']['response_notify_fragment_bytes'])}"
    )
    lines.append("}")
    lines.append("")
    lines.append("enum BMSGeneratedRegisterCatalog {")
    for name, kind, value in _collect_register_constants(catalog):
        swift_type = "Int" if kind == "int" else "UInt16"
        if kind == "int":
            lines.append(f"    static let {name}: {swift_type} = {value}")
        else:
            lines.append(f"    static let {name}: {swift_type} = 0x{value:04X}")
    lines.append("}")
    lines.append("")
    return "\n".join(lines)


